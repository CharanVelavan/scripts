        if ($curl) {
            Invoke-Native { & curl.exe -fL --retry 3 -sS -o $gcZip $GcloudUrl }
            if ($LASTEXITCODE -ne 0) { Fail "Could not download $GcloudUrl" }
        } else {
            $ProgressPreference = 'SilentlyContinue'
            Invoke-WebRequest -UseBasicParsing -Uri $GcloudUrl -OutFile $gcZip
        }
    }
    Say '      extracting ...'
    $tar = Get-Command tar.exe -ErrorAction SilentlyContinue
    $done = $false
    if ($tar) {
        Invoke-Native { & tar.exe -xf $gcZip -C $InstallDir }
        $done = ($LASTEXITCODE -eq 0)
    }
    if (-not $done) { Expand-Archive -Path $gcZip -DestinationPath $InstallDir -Force }
    Remove-Item -Force $gcZip -ErrorAction SilentlyContinue
    if (-not (Test-Path $gcBin)) { Fail 'The Google Cloud CLI archive did not contain google-cloud-sdk\bin\gcloud.cmd.' }
    $installBat = Join-Path $InstallDir 'google-cloud-sdk\install.bat'
    if (Test-Path $installBat) {
        # Optional post-install step; the CLI works without it, so never abort on a problem here.
        try {
            Invoke-Native { & cmd.exe /c "`"$installBat`" --quiet --usage-reporting=false --path-update=false --command-completion=false" 2>&1 | Out-Null }
        } catch {
            Warn "gcloud post-install step skipped: $($_.Exception.Message)"
        }
    }
}

# --- 3/4. PATH, PowerShell functions (kit's own installer picks Python and writes the profile) --------
Say '[3/6] Setting up PATH and the atlas command ...'
$kitInstaller = Join-Path $InstallDir 'install.ps1'
$hostExe = (Get-Process -Id $PID).Path
$installArgs = @('-NoProfile', '-ExecutionPolicy', 'Bypass', '-File', $kitInstaller, '-Quiet')
if ($OpencodeAlias) { $installArgs += '-OpencodeAlias' }
if ($Portable) { $installArgs += '-Portable' }
Invoke-Native { & $hostExe @installArgs }
if ($LASTEXITCODE -ne 0) { Fail 'install.ps1 failed (see the message above).' }

# --- 5. OpenCode (opt-in; Atlas needs the 1.19.x line) ---------------------------------------------
if ($InstallOpenCode) {
    $npm = Get-Command npm.cmd -ErrorAction SilentlyContinue
    if (-not $npm) {
        Warn 'npm not found, so OpenCode was not installed. Install Node.js (winget install OpenJS.NodeJS.LTS), reopen PowerShell, then:'
        Warn "  npm install --prefix `"$InstallDir\opencode`" opencode-ai@$OpenCodeVersion"
    } else {
        Say "[4/6] Installing OpenCode $OpenCodeVersion into $InstallDir\opencode ..."
        Invoke-Native { & npm.cmd install --prefix (Join-Path $InstallDir 'opencode') "opencode-ai@$OpenCodeVersion" --no-audit --no-fund | Out-Null }
        if ($LASTEXITCODE -ne 0) { Warn "npm install failed; install OpenCode $OpenCodeVersion yourself." }
    }
} else {
    Say '[4/6] OpenCode skipped. Atlas needs 1.19.x; to install it next to Atlas (needs Node.js):'
    Say "      npm install --prefix `"$InstallDir\opencode`" opencode-ai@$OpenCodeVersion"
}

