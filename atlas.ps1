$zip = [IO.Compression.ZipFile]::OpenRead($kitZip)
try {
    foreach ($entry in $zip.Entries) {
        $rel = $entry.FullName.Replace('/', $sep)
        $dest = [IO.Path]::GetFullPath((Join-Path $InstallDir $rel))
